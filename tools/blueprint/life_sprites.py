"""Art mode's moving life: sprite frames for animals, boats, flags and fires, plus the shore foam and
sea sparkle points. Writes the frames to assets/sprites/plan_art/life/ and src/blueprint/artLife.generated.ts.
Everything here is left off the painted base so the game can move it."""
import math, os, random, sys
from PIL import Image, ImageDraw
from shapely.geometry import Point
from shapely.prepared import prep

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', 'art'))
import pixel_props as pp

S = 6  # px per world unit, same as the base (the locked pixel scale)
ANIM = ('goat', 'pig', 'chicken', 'crow', 'parrot', 'crab', 'turtle', 'gull', 'rowboat_moored', 'fishing_boat', 'jolly_roger', 'flag', 'campfire')
REL = 'assets/sprites/plan_art/life'


def flag_frame(kind, f):
    s = S; im = Image.new('RGBA', (int(7 * s), int(9 * s)), (0, 0, 0, 0)); d = ImageDraw.Draw(im)
    d.line([0.6 * s, 9 * s, 0.6 * s, 0], fill=(80, 56, 36, 255), width=max(1, s // 2))
    col = (24, 24, 24, 255) if kind == 'jolly_roger' else (176, 52, 44, 255)
    wave = [0.0, 0.5, 0.0, -0.5] if f == 0 else [0.4, -0.2, -0.5, 0.2]
    top = [(0.8 + k * 1.6, 0.2 + wave[k]) for k in range(4)]
    bot = [(0.8 + k * 1.6, 3.4 + wave[k] * 0.8) for k in range(4)]
    d.polygon([(x * s, y * s) for x, y in top + bot[::-1]], fill=col)
    if kind == 'jolly_roger':
        d.ellipse([2.4 * s, (0.9 + wave[1] * 0.5) * s, 3.8 * s, (2.3 + wave[1] * 0.5) * s], fill=(236, 232, 222, 255))
    return pp._outline(im), (0.6 * s, 9 * s - 1)


def gull_frame(f):
    s = S; im = Image.new('RGBA', (int(5 * s), int(3 * s)), (0, 0, 0, 0)); d = ImageDraw.Draw(im)
    wy = 0.2 if f == 0 else 1.8
    d.line([0.2 * s, wy * s, 2.5 * s, 1.4 * s, 4.8 * s, wy * s], fill=(244, 244, 240, 255), width=max(2, s // 2))
    d.rectangle([2.2 * s, 1.1 * s, 2.9 * s, 1.8 * s], fill=(244, 244, 240, 255)); d.point((2.9 * s, 1.4 * s), fill=(240, 180, 50, 255))
    return pp._outline(im, (60, 64, 70, 255)), (2.5 * s, 1.5 * s)


def fire_frame(f):
    spr, anc = pp.critter(S, 'campfire', 1) or pp.prop(S, 'campfire', 0)
    if f:
        spr = spr.copy(); d = ImageDraw.Draw(spr); s = S
        d.polygon([(1.5 * s, 2.6 * s), (2.3 * s, 0.6 * s), (2.7 * s, 2.6 * s)], fill=(246, 166, 60, 255))
    return spr, anc


def frames(kind):
    if kind in ('jolly_roger', 'flag'): return [flag_frame(kind, f) for f in (0, 1)]
    if kind == 'gull': return [gull_frame(0), gull_frame(1)]
    if kind == 'campfire': return [fire_frame(0), fire_frame(1)]
    spr, anc = pp.get(S, kind, 0)
    if kind in ('chicken', 'crow', 'parrot'):  # second frame: head down, pecking
        f2 = Image.new('RGBA', spr.size, (0, 0, 0, 0)); w, h = spr.size
        f2.alpha_composite(spr.crop((0, 0, w, h)).transform(spr.size, Image.AFFINE, (1, 0, 0, 0, 1, -max(1, S // 3)), Image.NEAREST))
        return [(spr, anc), (f2, anc)]
    if kind == 'crab':
        f2 = spr.transpose(Image.FLIP_LEFT_RIGHT); return [(spr, anc), (f2, anc)]
    return [(spr, anc)]


PAINTED_LIFE = set()
LIFE_PLACES = {}
LIFE_KINDS = {}


ROOFS = []


def build(root, P, dress_props, coast, beach, no_foam=None):
    os.makedirs(f'{root}/{REL}', exist_ok=True)
    kinds = sorted({k for k, *_ in list(dress_props) + list(P.PROPS) if k in ANIM} | {'gull'})
    ts = ['// GENERATED by tools/blueprint/life_sprites.py — Art mode\'s moving life. Never hand-edit.',
          "import type { ImageSourcePropType } from 'react-native';", '',
          '/** kind -> frames, size in world units and anchor (fraction of width/height). */',
          'export const LIFE_SPRITES: Record<string, { frames: ImageSourcePropType[]; code?: ImageSourcePropType[]; w: number; h: number; ax: number; ay: number }> = {']
    for k in kinds:
        fr = frames(k)
        reqs, creqs = [], []
        for i, (im, anc) in enumerate(fr):
            if os.path.exists(f'{root}/assets/art_painted/life/{k}_{i}.png'):
                im.save(f'{root}/{REL}/{k}_{i}__code.png'); creqs.append(f"require('../../{REL}/{k}_{i}__code.png')")
                PAINTED_LIFE.add(f'{k}_{i}')
            painted = f'{root}/assets/art_painted/life/{k}_{i}.png'
            os.makedirs(f'{root}/docs/art_reference/life', exist_ok=True)
            im.resize((im.size[0] * 4, im.size[1] * 4), Image.NEAREST).save(f'{root}/docs/art_reference/life/{k}_{i}.png')
            (Image.open(painted).convert('RGBA') if os.path.exists(painted) else im).save(f'{root}/{REL}/{k}_{i}.png'); reqs.append(f"require('../../{REL}/{k}_{i}.png')")
        im, anc = fr[0]
        LIFE_KINDS[k] = dict(frames=len(fr), w=im.size[0] / S)
        code = f"code: [{', '.join(creqs)}], " if creqs else ''
        ts.append(f"  {k}: {{ frames: [{', '.join(reqs)}], {code}w: {im.size[0] / S:g}, h: {im.size[1] / S:g}, ax: {anc[0] / im.size[0]:.3f}, ay: {anc[1] / im.size[1]:.3f} }},")
    ts.append('};')
    crit = [(k, x, y) for k, x, y in list(dress_props) + list(P.PROPS) if k in ANIM]
    # nothing that walks may stand where a roof is drawn (the life layer draws above the buildings)
    from shapely.geometry import box as _b
    from shapely.ops import unary_union as _u
    roofs = _u([_b(*r) for r in ROOFS]) if ROOFS else None
    crit = [c for c in crit if c[0] in ('rowboat_moored', 'fishing_boat', 'gull') or roofs is None or not roofs.contains(Point(c[1], c[2]))]
    # gulls: over every shore and the harbour, a few flocks
    rng = random.Random(5)
    ring = coast.exterior if coast.geom_type == 'Polygon' else max(coast.geoms, key=lambda g: g.area).exterior
    for i in range(70):
        p = ring.interpolate(rng.uniform(0, ring.length)); crit.append(('gull', round(p.x, 1), round(p.y, 1)))
    LIFE_PLACES.clear()
    for k_, x_, y_ in crit: LIFE_PLACES.setdefault(k_, []).append((x_, y_))
    ts.append('/** [kind, x, y] island-relative, each moved by ArtLife. */')
    ts.append('export const LIFE_CRITTERS: [string, number, number][] = [' + ', '.join(f"['{k}', {x:g}, {y:g}]" for k, x, y in crit) + '];')
    # shore foam: points along the coast with their outward normal
    shore = []
    L = ring.length; step = 4.5
    for i in range(int(L / step)):
        a, b = ring.interpolate(i * step), ring.interpolate(i * step + 1)
        tx, ty = b.x - a.x, b.y - a.y; n = math.hypot(tx, ty) or 1
        nx, ny = ty / n, -tx / n
        if coast.contains(Point(a.x + nx * 2, a.y + ny * 2)): nx, ny = -nx, -ny
        if no_foam is not None and no_foam.contains(a): continue
        shore.append((a.x, a.y, nx, ny))
    ts.append('/** Shore foam: [x, y, outward nx, ny] every few units round the island. */')
    ts.append('export const LIFE_SHORE: [number, number, number, number][] = [' + ', '.join(f'[{x:.1f}, {y:.1f}, {nx:.2f}, {ny:.2f}]' for x, y, nx, ny in shore) + '];')
    sea_band = coast.buffer(80).difference(coast.buffer(20))  # open water only, never over rocks or the shallows
    sp = prep(sea_band); l, t, r, b = sea_band.bounds
    spark = []
    while len(spark) < 500:
        x, y = rng.uniform(l, r), rng.uniform(t, b)
        if sp.contains(Point(x, y)): spark.append((x, y))
    ts.append('/** Sea sparkles: points that glint in turn. */')
    ts.append('export const LIFE_SPARKLES: [number, number][] = [' + ', '.join(f'[{x:.0f}, {y:.0f}]' for x, y in spark) + '];')
    open(f'{root}/src/blueprint/artLife.generated.ts', 'w').write('\n'.join(ts) + '\n')
    return len(crit), len(shore)
